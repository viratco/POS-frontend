// Generates app/themes.css. Run after adding a colour var or changing a theme:  node scripts/themes.mjs
//
// Screens use --t-<hex> variables, one per original colour, so "classic" is the app's own look.
// Every other theme maps each of those to a step of its own colour ramp, matched by lightness,
// and recolours Tailwind's stone-* the same way. Status colours are not themed.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// key, hue (oklch), strength of tint, accent hue
export const THEMES = [
  ["matcha", 135, 1, 95],
  ["strawberry", 5, 1.1, 350],
  ["blueberry", 280, 1.05, 310],
  ["mango", 62, 1.15, 75],
  ["ocean", 215, 1, 185],
];

const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const L = [0.985, 0.965, 0.925, 0.87, 0.71, 0.54, 0.45, 0.38, 0.29, 0.23, 0.16];
const C = [0.018, 0.03, 0.048, 0.062, 0.07, 0.075, 0.075, 0.07, 0.055, 0.045, 0.03];

const toLin = (v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
const toGam = (v) => (v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055);

function hexToOklch(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => toLin(parseInt(hex.slice(i, i + 2), 16) / 255));
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  const a = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
  const bb = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
  return { L: 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s, C: Math.hypot(a, bb) };
}

function oklchToHex(l, c, h) {
  // Lower the chroma until the colour fits in sRGB.
  for (let k = c; ; k -= 0.002) {
    const a = k * Math.cos((h * Math.PI) / 180), b = k * Math.sin((h * Math.PI) / 180);
    const x = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
    const y = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
    const z = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;
    const rgb = [4.0767416621 * x - 3.3077115913 * y + 0.2309699292 * z, -1.2684380046 * x + 2.6097574011 * y - 0.3413193965 * z, -0.0041960863 * x - 0.7034186147 * y + 1.707614701 * z];
    if (k <= 0 || rgb.every((v) => v >= -0.0005 && v <= 1.0005)) {
      return "#" + rgb.map((v) => Math.round(toGam(Math.min(1, Math.max(0, v))) * 255).toString(16).padStart(2, "0")).join("");
    }
  }
}

function walk(dir, out = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.tsx?$/.test(f)) out.push(p);
  }
  return out;
}

const used = new Set();
for (const f of [...walk("app"), ...walk("components")]) for (const m of readFileSync(f, "utf8").matchAll(/--t-([0-9a-f]{6})/g)) used.add(m[1]);
const hexes = [...used].sort();

const STONE = `  --color-stone-50: oklch(98.5% 0.001 106.423);
  --color-stone-100: oklch(97% 0.001 106.424);
  --color-stone-200: oklch(92.3% 0.003 48.717);
  --color-stone-300: oklch(86.9% 0.005 56.366);
  --color-stone-400: oklch(70.9% 0.01 56.259);
  --color-stone-500: oklch(55.3% 0.013 58.071);
  --color-stone-600: oklch(44.4% 0.011 73.639);
  --color-stone-700: oklch(37.4% 0.01 67.558);
  --color-stone-800: oklch(26.8% 0.007 34.298);
  --color-stone-900: oklch(21.6% 0.006 56.043);
  --color-stone-950: oklch(14.7% 0.004 49.25);`;

let css = `/* Generated by scripts/themes.mjs. Don't edit by hand. */\n:root,\n[data-theme="classic"] {\n  --t-surface: #ffffff;\n${STONE}\n`;
css += hexes.map((h) => `  --t-${h}: #${h};`).join("\n") + "\n}\n";

for (const [key, hue, strength, accentHue] of THEMES) {
  const ramp = L.map((l, i) => oklchToHex(l, C[i] * strength, hue));
  css += `\nhtml[data-theme="${key}"],\n[data-theme="${key}"] {\n  --t-surface: ${oklchToHex(0.985, 0.014 * strength, hue)};\n`;
  css += STEPS.map((s, i) => `  --color-stone-${s}: ${ramp[i]};`).join("\n") + "\n";
  for (const h of hexes) {
    const c = hexToOklch("#" + h);
    if (c.C > 0.07) {
      // Gold and tan details follow the theme's accent, at the same lightness.
      css += `  --t-${h}: ${oklchToHex(c.L, 0.11, accentHue)};\n`;
    } else {
      let best = 0;
      L.forEach((l, i) => { if (Math.abs(l - c.L) < Math.abs(L[best] - c.L)) best = i; });
      css += `  --t-${h}: ${ramp[best]};\n`;
    }
  }
  css += "}\n";
}
writeFileSync("app/themes.css", css);

// Readability check: text on the page background should reach 4.5:1.
const lum = (hex) => { const [r, g, b] = [1, 3, 5].map((i) => toLin(parseInt(hex.slice(i, i + 2), 16) / 255)); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
for (const [key, hue, strength] of THEMES) {
  const r = L.map((l, i) => oklchToHex(l, C[i] * strength, hue));
  console.log(key.padEnd(11), "dark text", ratio(r[9], r[0]).toFixed(1), "| muted text", ratio(r[5], r[0]).toFixed(1), "| white on button", ratio("#ffffff", r[9]).toFixed(1));
}
console.log(hexes.length, "colours themed");
